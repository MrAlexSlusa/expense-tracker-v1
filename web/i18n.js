function localizedQuizText(questionId, optionId) {
  const lang = QUIZ_CONTENT[currentLang] || QUIZ_CONTENT.en;
  const fallback = QUIZ_CONTENT.en[questionId];
  const q = lang[questionId] || fallback;
  if (!optionId) return q.text;
  return q.options[optionId] || fallback.options[optionId] || optionId;
}

let currentLang = "en";

function setLang(lang) {
  currentLang = TRANSLATIONS[lang] ? lang : "en";
  document.documentElement.lang = currentLang;
}

function t(key, vars) {
  let str = (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS.en[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => { str = str.replace(`{${k}}`, v); });
  }
  return str;
}

function translateError(message) {
  const key = BACKEND_ERROR_KEYS[message];
  return key ? t(key) : message;
}

function localeForLang() {
  return LOCALE_MAP[currentLang] || "en-US";
}

function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    // Elements with element children (e.g. labels wrapping an input) only
    // get their first text node replaced, so the child input survives.
    const textNode = Array.from(el.childNodes).find((n) => n.nodeType === Node.TEXT_NODE);
    if (textNode) {
      textNode.textContent = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}
